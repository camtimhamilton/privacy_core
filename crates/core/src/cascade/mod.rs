//! Каскады детекции.
//!
//! # Порядок и правила
//!
//! Каскады применяются по возрастанию уровня, и **более поздний каскад не
//! отменяет находку более раннего**, а только повышает уверенность. Причина:
//! на форматных типах правило точнее модели, и модель не должна затирать
//! результат контрольной суммы.
//!
//! | Каскад | Уровень | Зависимости |
//! |---|---|---|
//! | [`format`] | L0 | нет: арифметика и словари меток |
//! | [`super::bridge::ExternalDetector`] | L0a | нет: точное сравнение строк |
//! | модель | L2 | ONNX, отключена по умолчанию |
//! | диалог | L3 | ссылки и реестр сессии |

pub mod checksum;
pub mod format;

pub use checksum::{
    is_valid_inn_legal, is_valid_inn_person, is_valid_ogrn, is_valid_ogrnip, is_valid_snils,
};
pub use format::{FormatCascade, FormatRule, RULES};
