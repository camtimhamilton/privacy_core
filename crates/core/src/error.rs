//! Ошибки и поведение при сбое.
//!
//! Инвариант I4 (fail-closed): **любой сбой детекции не приводит к отправке
//! исходного текста**. Это не пожелание, а свойство ядра, которое проверяется
//! тестами в `tests/invariant_i4_fail_closed.rs`.
//!
//! Отдельно различаются два случая, которые легко перепутать:
//!
//! * [`CoreError`] — сбой, после которого вызывающая сторона обязана
//!   **не отправлять** текст. Ядро вернуло ошибку, значит результата нет.
//! * [`FailureBehavior`] — настройка политики: что делать, если каскад
//!   недоступен. Значение по умолчанию — [`FailureBehavior::Block`].

use core::fmt;

/// Ошибка ядра.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CoreError {
    /// Каскад включён политикой, но не может работать.
    ///
    /// Примеры: не загружена модель для L2, отключён диалоговый каскад при
    /// политике, которая его требует.
    DetectorUnavailable {
        /// Имя каскада, который недоступен.
        cascade: &'static str,
        /// Причина в свободной форме, без исходных значений (инвариант I10).
        reason: String,
    },
    /// Сбой внутри каскада: паника, испорченное состояние, ошибка провайдера.
    CascadeFailed {
        /// Имя каскада.
        cascade: &'static str,
        /// Описание без исходных значений.
        reason: String,
    },
    /// Карта соответствий недоступна или повреждена.
    ///
    /// Повреждённая карта **не заменяется пустой**: это привело бы к отправке
    /// исходного текста при следующем вызове.
    MappingUnavailable {
        /// Описание без исходных значений.
        reason: String,
    },
    /// Не удалось прочитать или создать ключ шифрования карты.
    KeyUnavailable {
        /// Описание без исходных значений.
        reason: String,
    },
    /// Текст не является корректным UTF-8 на границах спанов, либо найденный
    /// спан выходит за пределы текста.
    ///
    /// Считается дефектом детектора, а не ошибкой вызывающей стороны.
    InvalidSpan {
        /// Границы, которые оказались некорректны.
        span: (usize, usize),
    },
    /// Значение относится к специальным категориям, обезличивание которых
    /// законом не допускается (ч. 1 ст. 10 152-ФЗ).
    ///
    /// Реакция — **блокировка отправки**, а не подмена. Подробности —
    /// в `phase-0/05-legal/README.md`.
    SpecialCategory {
        /// Тип, из-за которого отправка заблокирована.
        entity_type: String,
    },
    /// Внутренняя несогласованность: сработала защита от нарушения инварианта.
    ///
    /// Возвращается вместо паники там, где паника была бы дороже ошибки.
    InvariantViolation {
        /// Идентификатор инварианта, например `I1`.
        invariant: &'static str,
        /// Что именно обнаружено, без исходных значений.
        detail: String,
    },
}

impl fmt::Display for CoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CoreError::DetectorUnavailable { cascade, reason } => {
                write!(f, "каскад {cascade} недоступен: {reason}")
            }
            CoreError::CascadeFailed { cascade, reason } => {
                write!(f, "сбой каскада {cascade}: {reason}")
            }
            CoreError::MappingUnavailable { reason } => write!(f, "карта недоступна: {reason}"),
            CoreError::KeyUnavailable { reason } => write!(f, "ключ недоступен: {reason}"),
            CoreError::InvalidSpan { span } => {
                write!(f, "некорректный спан: {}..{}", span.0, span.1)
            }
            CoreError::SpecialCategory { entity_type } => write!(
                f,
                "обнаружены данные специальной категории ({entity_type}), отправка заблокирована"
            ),
            CoreError::InvariantViolation { invariant, detail } => {
                write!(f, "нарушение инварианта {invariant}: {detail}")
            }
        }
    }
}

impl std::error::Error for CoreError {}

/// Результат операций ядра.
pub type Result<T> = core::result::Result<T, CoreError>;

/// Поведение при недоступности каскада.
///
/// Значение по умолчанию — [`FailureBehavior::Block`]. Режим «пропустить»
/// существует только как явный выбор с предупреждением и **нарушает I4**,
/// поэтому в отчёте он помечается отдельно.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum FailureBehavior {
    /// Не отправлять ничего. Значение по умолчанию.
    #[default]
    Block,
    /// Продолжить без этого каскада, понизив уверенность и пометив это в отчёте.
    DegradeAndWarn,
    /// Пропустить текст без обезличивания.
    ///
    /// Существует для полноты модели, но по умолчанию недоступен: включение
    /// требует явного подтверждения вызывающей стороны.
    PassThrough,
}

impl FailureBehavior {
    /// Сохраняет ли этот режим инвариант I4.
    pub const fn preserves_fail_closed(&self) -> bool {
        !matches!(self, FailureBehavior::PassThrough)
    }
}
