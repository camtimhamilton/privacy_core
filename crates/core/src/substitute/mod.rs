/// Запрос на подмену.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SubstitutionRequest {
    /// Тип сущности, для которого нужна подмена.
    pub entity_type: EntityTypeId,
    /// Нормализованный ключ, чтобы подмена была устойчивой в сессии.
    pub key: String,
    /// Вид подмены.
    pub kind: SubstitutionKind,
}

/// Генератор подмен.
pub trait SubstitutionGenerator {
    /// Имя генератора для отчёта.
    fn name(&self) -> &'static str;

    /// Версия генератора. Меняется, когда меняется распределение подмен.
    fn version(&self) -> u32;

    /// Создаёт подмену.
    ///
    /// Обязан быть детерминированным относительно внутреннего состояния seed:
    /// при одинаковом состоянии и одинаковом запросе результат совпадает.
    fn generate(&mut self, request: &SubstitutionRequest) -> String;
}
