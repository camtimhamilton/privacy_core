//! Генерация подмен.
//!
//! # Обязательные свойства
//!
//! 1. **Форматная валидность.** Фейковый ИНН проходит контрольную сумму,
//!    фейковый телефон разбирается по шаблону. Иначе ответ внешней модели
//!    выглядит подозрительно, а восстановление сбивается.
//! 2. **Отсутствие коллизий.** Фейк не совпадает ни с одним реальным
//!    значением сессии и ни с другим фейком (I5).
//! 3. **Проверка по реестрам.** Фейк не должен совпасть с существующим
//!    реальным реквизитом. Для ИНН и ОГРН это критично: это публичные
//!    реестровые номера, и валидная контрольная сумма **не означает**,
//!    что номер вымышленный.
//! 4. **Детерминированность от seed.** Одна и та же сессия при том же seed
//!    даёт те же подмены, иначе инцидент невозможно воспроизвести.
//! 5. **Обратимость.** Восстановление однозначно, даже если фейк встретился
//!    в ответе дважды.

